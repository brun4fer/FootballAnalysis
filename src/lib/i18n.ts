export function translate(key: string, language: AppLanguage) {
  return (language === "pt" ? toPortuguese : toEnglish).get(key) ?? key;
}

export function translateUiText(original: string, language: AppLanguage) {
  const value = original.trim();
  if (!value) return original;
  const exact = translate(value, language);
  const translated = exact === value ? translateDynamicText(value, language) : exact;
  return translated === value ? original : preserveOuterWhitespace(original, translated);
}
